"""Per-type data capture, recursive on both sides (§2.2).

Python side uses a ``json.JSONEncoder`` subclass whose ``default()`` handles
nested containers automatically.  R side uses a single recursive dispatcher
(``.r2py_serialize_var``) whose adapters return R lists/scalars; a single outer
``jsonlite::toJSON`` is applied at the top level so the resulting JSON shape
matches what the Python encoder produces.

Unknown types go to uncapturable (EffectBundle.uncapturable), never silently
skipped (D2).
"""
from __future__ import annotations

import datetime as _dt
import json as _json
import math as _math
from pathlib import Path
from typing import Any


def _sanitize_non_finite(obj: Any) -> Any:
    """Replace non-finite floats to match R's jsonlite output.

    nan → None  (jsonlite na='null' maps both NA and NaN to null)
    inf → "Inf", -inf → "-Inf"  (jsonlite wraps in strings)
    """
    if isinstance(obj, float):
        if _math.isnan(obj):
            return None
        if _math.isinf(obj):
            return "Inf" if obj > 0 else "-Inf"
        return obj
    if isinstance(obj, dict):
        return {k: _sanitize_non_finite(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_sanitize_non_finite(v) for v in obj]
    return obj


# ---------------------------------------------------------------------------
# Module-level _R2PyEncoder — used by callers that need to serialize R-side
# captured data (e.g. loop._write_data_sidecar).  The Python preamble text
# generated by build_py_preamble() defines an *equivalent* class inline so the
# sandbox doesn't need to import this module.  Keep the two in lockstep.
# ---------------------------------------------------------------------------

class _R2PyEncoder(_json.JSONEncoder):
    def default(self, obj: Any) -> Any:
        try:
            import numpy as _np  # type: ignore[import]
            if isinstance(obj, _np.generic):
                return obj.item()
            if isinstance(obj, _np.ndarray):
                return obj.tolist()
        except ImportError:
            pass
        if isinstance(obj, _dt.datetime):
            return obj.strftime("%Y-%m-%dT%H:%M:%S")
        if isinstance(obj, _dt.date):
            return obj.isoformat()
        try:
            import pandas as _pd  # type: ignore[import]
            if isinstance(obj, _pd.Timestamp):
                return None if _pd.isna(obj) else obj.strftime("%Y-%m-%dT%H:%M:%S")
            if isinstance(obj, _pd.DataFrame):
                result: dict = {}
                for _c in obj.columns:
                    _series = obj[_c]
                    if _pd.api.types.is_datetime64_any_dtype(_series):
                        result[_c] = [None if _pd.isna(v) else v.strftime("%Y-%m-%d") for v in _series]
                    else:
                        result[_c] = _series.tolist()
                return result
            if isinstance(obj, _pd.Series):
                if _pd.api.types.is_datetime64_any_dtype(obj):
                    return [None if _pd.isna(v) else v.strftime("%Y-%m-%d") for v in obj]
                return obj.tolist()
            if isinstance(obj, _pd.Categorical):
                return list(obj)
        except ImportError:
            pass
        if isinstance(obj, (set, frozenset)):
            return list(obj)
        return super().default(obj)


# ---------------------------------------------------------------------------
# R adapter registry — recursive (serializers return R objects, not JSON)
# ---------------------------------------------------------------------------

# Each entry: (R predicate expression, R serializer expression).  Both use
# ``{var}`` as the placeholder for the current value.  The serializer must
# return an R object (list / atomic vector / scalar) — NOT a JSON string —
# so the outer ``jsonlite::toJSON`` at the top of the epilogue can produce a
# single coherent JSON document.  Container serializers should call
# ``.r2py_serialize_var()`` recursively on their elements.
_R_ADAPTERS: list[tuple[str, str]] = []


def register_r_adapter(type_pred: str, serializer: str) -> None:
    """Register an R-side adapter.  See module docstring for the contract."""
    _R_ADAPTERS.append((type_pred, serializer))


# Built-in R adapters — ordered most-specific first.
# Date / POSIXct → ISO strings (mirrors Python's .isoformat()).
register_r_adapter(
    "inherits({var}, 'Date')",
    "format({var}, '%Y-%m-%d')",
)
register_r_adapter(
    "inherits({var}, 'POSIXct') || inherits({var}, 'POSIXlt')",
    "format({var}, '%Y-%m-%dT%H:%M:%S')",
)
# Factor → character vector (mirrors pandas.Categorical → list(obj)).
register_r_adapter(
    "is.factor({var})",
    "as.character({var})",
)
# data.frame → dict of column-name → recursed column.
register_r_adapter(
    "is.data.frame({var})",
    "lapply({var}, .r2py_serialize_var)",
)
# htmltools / shiny tags → rendered HTML string.
register_r_adapter(
    "inherits({var}, 'htmltools_tag') || inherits({var}, 'shiny.tag')",
    "as.character(htmltools::renderTags({var})$html)",
)
# lm / glm → structured summary, each component recursed.
register_r_adapter(
    "inherits({var}, 'lm') || inherits({var}, 'glm')",
    (
        "list("
        "coefficients = .r2py_serialize_var(as.list(coef({var})))"
        ", residuals = .r2py_serialize_var(as.list(residuals({var})))"
        ", fitted = .r2py_serialize_var(as.list(fitted({var})))"
        ")"
    ),
)
# S4 objects → dict of slot-name → recursed slot.
register_r_adapter(
    "isS4({var})",
    (
        "{ .r2py_slots <- slotNames({var}); "
        ".r2py_res <- lapply(.r2py_slots, function(.s) .r2py_serialize_var(slot({var}, .s))); "
        "names(.r2py_res) <- .r2py_slots; "
        ".r2py_res }"
    ),
)
# Generic list (including named lists) → recurse into elements.
register_r_adapter(
    "is.list({var})",
    "lapply({var}, .r2py_serialize_var)",
)
# vctrs_vctr (haven_labelled, etc.) → strip class so jsonlite doesn't recurse.
register_r_adapter(
    "inherits({var}, 'vctrs_vctr')",
    "unclass({var})",
)
# Plain atomic vectors / scalars → return as-is; jsonlite encodes them at the top.
register_r_adapter(
    "is.atomic({var}) || is.numeric({var}) || is.character({var}) || is.logical({var})",
    "{var}",
)


