def collect(workdir: Path) -> dict:
    """Read _r2py_state.json and _r2py_uncapturable.json → EffectBundle fields.

    Backward-compatible: handles both the new R format (single coherent JSON
    document with structured values) and the legacy format (per-variable JSON
    strings that need a second ``json.loads`` pass).
    """
    import json

    data: dict = {}
    uncapturable: list[str] = []

    state_file = workdir / "_r2py_state.json"
    if state_file.exists():
        try:
            raw = json.loads(state_file.read_text(encoding="utf-8"))
            for k, v in raw.items():
                # Legacy R epilogue stored values as JSON-encoded strings; the
                # new epilogue stores them as structured values.  Try decode
                # for the legacy case only — fall through for already-decoded.
                if isinstance(v, str):
                    try:
                        decoded = json.loads(v)
                    except (json.JSONDecodeError, ValueError):
                        decoded = v
                    data[k] = decoded
                else:
                    data[k] = v
        except Exception:
            pass

    unc_file = workdir / "_r2py_uncapturable.json"
    if unc_file.exists():
        try:
            uncapturable = json.loads(unc_file.read_text(encoding="utf-8"))
        except Exception:
            pass

    return {"data": data, "uncapturable": uncapturable}


# ---------------------------------------------------------------------------
# Sidecar payload helper (used by loop.py and stage4/verifier.py)
# ---------------------------------------------------------------------------

def serialize_bundle_data(data: dict, *, indent: int | None = None) -> str:
    """Serialize an EffectBundle.data dict to JSON via ``_R2PyEncoder``.

    Single source of truth for the data-loading shim's payload format — used
    both by ``loop._write_data_sidecar`` (on-disk artifact for manual debugging)
    and ``stage4.verifier._build_sidecar_payload`` (in-sandbox copy for
    equivalence testing).  Keeping these two paths in lockstep ensures a new
    type added to ``_R2PyEncoder`` is automatically supported by both.
    """
    encoded = _json.loads(_json.dumps(data or {}, cls=_R2PyEncoder, allow_nan=True))
    return _json.dumps(_sanitize_non_finite(encoded), indent=indent)
