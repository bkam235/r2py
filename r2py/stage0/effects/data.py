PY_EPILOGUE_TEMPLATE = """\
import json as _r2py_json

_r2py_state = {}
_r2py_uncapturable = []

for _r2py_k, _r2py_v in list(globals().items()):
    if _r2py_k.startswith('_r2py_') or _r2py_k.startswith('__'):
        continue
    if callable(_r2py_v) and not isinstance(_r2py_v, type):
        _r2py_vtype = type(_r2py_v)
        _r2py_tname = _r2py_vtype.__name__
        if _r2py_tname in ('function', 'builtin_function_or_method', 'method',
                            'method-wrapper', 'method_descriptor'):
            continue
        import inspect as _r2py_inspect
        try:
            _r2py_sig = _r2py_inspect.signature(_r2py_v)
            _r2py_fmls = list(_r2py_sig.parameters.keys())
        except (ValueError, TypeError):
            _r2py_fmls = []
        if set(_r2py_fmls) <= {'args', 'kwargs', 'self', 'cls'}:
            for _r2py_wattr in dir(_r2py_v):
                if _r2py_wattr.startswith('__') and _r2py_wattr != '__wrapped__':
                    continue
                _r2py_inner = getattr(_r2py_v, _r2py_wattr, None)
                if _r2py_inner is None or not callable(_r2py_inner) or type(_r2py_inner).__name__ != 'function':
                    continue
                try:
                    _r2py_inner_fmls = list(_r2py_inspect.signature(_r2py_inner).parameters.keys())
                    if not set(_r2py_inner_fmls) <= {'args', 'kwargs', 'self', 'cls'}:
                        _r2py_fmls = _r2py_inner_fmls
                        break
                except (ValueError, TypeError):
                    pass
        _r2py_meta = {
            '__r2py_callable_meta__': True,
            'class': [_r2py_vtype.__name__],
            'formals': _r2py_fmls,
            'attributes': {},
        }
        for _r2py_an in ('name', 'dispatch_args'):
            _r2py_av = getattr(_r2py_v, _r2py_an, None)
            if _r2py_av is not None:
                _r2py_meta['attributes'][_r2py_an] = _r2py_av
        _r2py_state[_r2py_k] = _r2py_meta
        continue
    _r2py_serialized, _r2py_ok = _r2py_try_serialize(_r2py_k, _r2py_v)
    if not _r2py_ok:
        _r2py_uncapturable.append(_r2py_k)
        continue
    if isinstance(_r2py_serialized, dict) and '__r2py_callable_meta__' in _r2py_serialized:
        _r2py_serialized = {k: v for k, v in _r2py_serialized.items() if k != '__r2py_callable_meta__'}
    _r2py_state[_r2py_k] = _r2py_serialized

with open('_r2py_state.json', 'w', encoding='utf-8') as _f:
    _r2py_json.dump(_r2py_state, _f)
with open('_r2py_uncapturable.json', 'w', encoding='utf-8') as _f:
    _r2py_json.dump(_r2py_uncapturable, _f)
"""


def build_py_preamble() -> str:
    """Build the Python preamble that installs the encoder + helper.

    The encoder's ``default()`` does an ``isinstance`` cascade and is invoked
    recursively by ``json.dumps`` for every non-native element encountered in
    the object graph — including elements inside lists / dicts returned from
    ``default()`` itself.  This is the structural fix for the v0.1
    JSON-opacity trap (nested ``datetime.date`` inside a DataFrame column,
    nested ``np.generic`` inside a Series, etc.).

    Adding a new supported type = one ``isinstance`` branch in ``default()``.
    """
    return """\
import json as _r2py_json
import datetime as _r2py_dt
import math as _r2py_math


def _r2py_sanitize(obj):
    if isinstance(obj, float):
        if _r2py_math.isnan(obj):
            return None
        if _r2py_math.isinf(obj):
            return "Inf" if obj > 0 else "-Inf"
        return obj
    if isinstance(obj, dict):
        return {k: _r2py_sanitize(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_r2py_sanitize(v) for v in obj]
    return obj


class _R2PyEncoder(_r2py_json.JSONEncoder):
    def default(self, obj):
        # numpy scalars and arrays
        try:
            import numpy as _np
            if isinstance(obj, _np.generic):
                return obj.item()
            if isinstance(obj, _np.ndarray):
                return obj.tolist()
        except ImportError:
            pass
        # datetime — datetime before date (datetime is a subclass of date)
        if isinstance(obj, _r2py_dt.datetime):
            return obj.strftime('%Y-%m-%dT%H:%M:%S')
        if isinstance(obj, _r2py_dt.date):
            return obj.isoformat()
        # pandas
        try:
            import pandas as _pd
            if isinstance(obj, _pd.Timestamp):
                return None if _pd.isna(obj) else obj.strftime('%Y-%m-%dT%H:%M:%S')
            if isinstance(obj, _pd.DataFrame):
                result = {}
                for _c in obj.columns:
                    _series = obj[_c]
                    if _pd.api.types.is_datetime64_any_dtype(_series):
                        result[_c] = [None if _pd.isna(v) else v.strftime('%Y-%m-%d') for v in _series]
                    else:
                        result[_c] = _series.tolist()
                return result
            if isinstance(obj, _pd.Series):
                if _pd.api.types.is_datetime64_any_dtype(obj):
                    return [None if _pd.isna(v) else v.strftime('%Y-%m-%d') for v in obj]
                return obj.tolist()
            if isinstance(obj, _pd.Categorical):
                return list(obj)
        except ImportError:
            pass
        # sets — useful for env captures
        if isinstance(obj, (set, frozenset)):
            return list(obj)
        return super().default(obj)


def _r2py_try_serialize(name, obj):
    \"\"\"Round-trip ``obj`` through ``_R2PyEncoder``, sanitizing non-finite floats.

    Returns ``(json_safe_value, True)`` on success — the value is pure Python
    (dict/list/str/number/bool/None) and can be re-serialized without a custom
    encoder.  Returns ``(None, False)`` for anything the encoder cannot handle.
    \"\"\"
    try:
        raw = _r2py_json.dumps(obj, cls=_R2PyEncoder, allow_nan=True)
        return _r2py_sanitize(_r2py_json.loads(raw, parse_constant=lambda c: {
            'NaN': None, 'Infinity': 'Inf', '-Infinity': '-Inf',
        }.get(c))), True
    except (TypeError, ValueError):
        return None, False
"""


