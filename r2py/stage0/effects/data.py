R_PREAMBLE = """\
library(jsonlite)
.r2py_uncapturable <- character(0)
"""


def build_r_serializer_fn() -> str:
    """Return R code defining ``.r2py_serialize_var(.r2py_obj)``.

    The function dispatches on the registered adapters in registration order.
    Each adapter's serializer returns an R object (list / vector / scalar).
    Functions and environments return ``NULL`` (uncapturable).  Anything that
    raises or has no matching adapter returns the string ``'__uncapturable__'``
    so the caller can route it to the uncapturable list.

    Note: ``'__uncapturable__'`` is a sentinel string returned from this
    function, NOT a JSON value — callers must check for it before serializing.
    """
    dispatch_lines: list[str] = []
    for i, (pred_tmpl, ser_tmpl) in enumerate(_R_ADAPTERS):
        pred = pred_tmpl.replace("{var}", ".r2py_obj")
        ser = ser_tmpl.replace("{var}", ".r2py_obj")
        keyword = "if" if i == 0 else "} else if"
        dispatch_lines.append(f"    {keyword} ({pred}) {{")
        dispatch_lines.append(f"      tryCatch({ser}, error = function(e) '__uncapturable__')")
    if dispatch_lines:
        dispatch_lines.append("    } else {")
        dispatch_lines.append("      '__uncapturable__'")
        dispatch_lines.append("    }")
    else:
        dispatch_lines.append("    '__uncapturable__'")
    body = "\n".join(dispatch_lines)
    return (
        ".r2py_serialize_var <- function(.r2py_obj) {\n"
        "  if (is.null(.r2py_obj)) return(NULL)\n"
        "  if (is.environment(.r2py_obj)) return(NULL)\n"
        "  if (is.function(.r2py_obj)) {\n"
        "    .r2py_cls <- class(.r2py_obj)\n"
        "    if (identical(.r2py_cls, 'function')) return(NULL)\n"
        "    .r2py_fmls <- tryCatch(names(formals(.r2py_obj)), error = function(e) character(0))\n"
        "    .r2py_attrs <- list()\n"
        "    for (.r2py_an in c('name', 'dispatch_args')) {\n"
        "      .r2py_av <- tryCatch(attr(.r2py_obj, .r2py_an), error = function(e) NULL)\n"
        "      if (!is.null(.r2py_av)) .r2py_attrs[[.r2py_an]] <- .r2py_av\n"
        "    }\n"
        "    return(list(\n"
        "      `__r2py_callable_meta__` = TRUE,\n"
        "      class = as.list(.r2py_cls),\n"
        "      formals = as.list(.r2py_fmls),\n"
        "      attributes = .r2py_attrs\n"
        "    ))\n"
        "  }\n"
        "  tryCatch({\n"
        f"{body}\n"
        "  }, error = function(e) '__uncapturable__')\n"
        "}\n"
    )


def build_r_epilogue() -> str:
    """Build the R data capture epilogue from the current ``_R_ADAPTERS``.

    Walks ``.GlobalEnv``, recursively serializes each variable via
    ``.r2py_serialize_var``, assembles them into a single R named list, then
    emits one coherent JSON document via ``jsonlite::toJSON``.  Uncapturable
    variables are recorded separately.
    """
    return (
        build_r_serializer_fn()
        + "# r2py data capture: serialize all globals to _r2py_state.json\n"
        ".r2py_state <- list()\n"
        ".r2py_vars <- ls(envir = .GlobalEnv)\n"
        ".r2py_vars <- .r2py_vars[!startsWith(.r2py_vars, '.r2py_')]\n"
        "for (.r2py_v in .r2py_vars) {\n"
        "  .r2py_obj <- get(.r2py_v, envir = .GlobalEnv)\n"
        "  .r2py_serialized <- .r2py_serialize_var(.r2py_obj)\n"
        "  if (is.null(.r2py_serialized) || identical(.r2py_serialized, '__uncapturable__')) {\n"
        "    .r2py_uncapturable <- c(.r2py_uncapturable, .r2py_v)\n"
        "  } else {\n"
        "    .r2py_state[[.r2py_v]] <- .r2py_serialized\n"
        "  }\n"
        "}\n"
        "writeLines(jsonlite::toJSON(.r2py_state, auto_unbox=TRUE, na='null', force=TRUE), '_r2py_state.json')\n"
        "writeLines(jsonlite::toJSON(.r2py_uncapturable), '_r2py_uncapturable.json')\n"
    )


